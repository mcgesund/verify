#!/usr/bin/env node
// Creates the demo files in examples/ with freshly generated demo keys.
//
//   node examples/generate.js
//
// Everything is made up: practice, reviews, document IDs, log entries.
// The keys are generated anew on every run (Ed25519, ML-DSA-87,
// SLH-DSA-SHA2-256f), sign everything in this one run and are then
// discarded. Private keys are never written to disk.
// The demo keys are NOT in McGesund's key directory.
//
// Network: only the SHA-256 digests (key commitments, envelopes, signed tree
// head) are sent to public OpenTimestamps calendars. The proofs are then
// "anchoring" (pending); `node examples/update.js` adds the Bitcoin
// confirmation later.
import fs from 'node:fs';
import { createHash, generateKeyPairSync, randomBytes, sign as nodeSign } from 'node:crypto';
import { encode } from 'cbor-x';
import { ml_dsa87 } from '@noble/post-quantum/ml-dsa.js';
import { slh_dsa_sha2_256f } from '@noble/post-quantum/slh-dsa.js';
import { recordHash, sha256hex } from '../lib/record-hash.js';
import { leafHash, merkleRoot, verifyTreeHead, verifyReviewInLog } from '../lib/transparency-log.js';
import { readEnvelope } from '../lib/envelope.js';
import { verifyPackage } from '../lib/verify.js';
import { proofDigest } from '../lib/timestamp.js';
import { writeProof } from '../lib/opentimestamps.js';
import { stamp } from './calendar.js';

const DEMO_NOTE =
  'Demo data signed with demo keys generated by examples/generate.js. Not a McGesund review; the demo keys are not in McGesund\'s key directory.';
const OUT = new URL('./', import.meta.url);

const b64 = (b) => Buffer.from(b).toString('base64');
const b64url = (b) => Buffer.from(b).toString('base64').replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
const randomId = () => {
  const chars = 'abcdefghijklmnopqrstuvwxyz0123456789';
  return Array.from(randomBytes(24), (x) => chars[x % chars.length]).join('');
};
const iso = (ms) => new Date(ms).toISOString();
const sec = (ms) => Math.floor(ms / 1000);

// ---------------------------------------------------------------------------
// Demo keys (memory only)
// ---------------------------------------------------------------------------

const now = Date.now();
const HOUR = 3600e3;
const DAY = 24 * HOUR;
const validFrom = new Date(now - 2 * DAY);
validFrom.setUTCHours(0, 0, 0, 0);
const validUntil = new Date(validFrom);
validUntil.setUTCFullYear(validUntil.getUTCFullYear() + 2);

const edPair = generateKeyPairSync('ed25519');
const edPub = Buffer.from(edPair.publicKey.export({ format: 'jwk' }).x, 'base64url');
const ml = ml_dsa87.keygen(randomBytes(32));
const slh = slh_dsa_sha2_256f.keygen(randomBytes(96));

const KEYS = {
  ed: {
    kid: 'demo-ed', algorithm: 'ed', algorithmName: 'Ed25519', standard: 'RFC 8032',
    pub: edPub, sign: (m) => nodeSign(null, Buffer.from(m), edPair.privateKey),
  },
  'ml-dsa-87': {
    kid: 'demo-mldsa87', algorithm: 'ml-dsa-87', algorithmName: 'ML-DSA-87', standard: 'FIPS 204',
    pub: ml.publicKey, sign: (m) => ml_dsa87.sign(m, ml.secretKey),
  },
  'slh-dsa-256f': {
    kid: 'demo-slh256f', algorithm: 'slh-dsa-256f', algorithmName: 'SLH-DSA-SHA2-256f', standard: 'FIPS 205',
    pub: slh.publicKey, sign: (m) => slh_dsa_sha2_256f.sign(m, slh.secretKey),
  },
};
const ED = KEYS.ed;
const ML = KEYS['ml-dsa-87'];
const SLH = KEYS['slh-dsa-256f'];

// Envelope "MCG1:" + base64url(CBOR([version, payload, edSig(, pqList)])), as in the backend.
function envelope(payload, pq = []) {
  const payloadBytes = encode({ ...payload, ...(pq.length ? { pv: pq.map((k) => k.algorithm) } : {}), kid: ED.kid });
  const edSig = ED.sign(payloadBytes);
  const stamps = pq.map((k) => ({ variant: k.algorithm, kid: k.kid, sig: Buffer.from(k.sign(payloadBytes)) }));
  const arr = pq.length
    ? [4, payloadBytes, edSig, stamps.map((s) => [s.variant, s.kid, s.sig])]
    : [3, payloadBytes, edSig];
  return { envelope: 'MCG1:' + b64url(encode(arr)), payloadBytes, stamps };
}
const stamp = (k, sig) => ({ variant: k.algorithm, kid: k.kid, sig: b64(sig), pubkey: b64(k.pub), format: 'v1' });

// ---------------------------------------------------------------------------
// Made-up practice and QR code (origin)
// ---------------------------------------------------------------------------

const practice = { name: 'Example Practice Sampletown', documentId: randomId() };
const qrPayload = { v: 1, iat: sec(validFrom.getTime() + HOUR), exp: sec(validUntil.getTime()), typ: 'rev-wall', fid: practice.documentId };
const qr = envelope(qrPayload); // QR content stays v3 (Ed25519 only); origin stamps sit next to it
const qrAttestation = {
  envelope: qr.envelope,
  stamps: [ML, SLH].map((k) => stamp(k, k.sign(qr.payloadBytes))),
  payloadHash: createHash('sha256').update(qr.payloadBytes).digest('base64'),
  revoked: false,
};
const qh = sha256hex(qr.envelope);

// ---------------------------------------------------------------------------
// Reviews
// ---------------------------------------------------------------------------

const record = (Content, hearts, geoDistance) => ({
  Content,
  AverageRating: hearts.reduce((a, b) => a + b, 0) / hearts.length,
  ValueRating: hearts[0],
  ServiceRating: hearts[1],
  CleanlinessRating: hearts[2],
  QualityRating: hearts[3],
  productLabel: null,
  eventLabel: null,
  geoStatus: 'ok',
  geoVerified: true,
  geoDistance,
  viaRotatingToken: false,
});
const withQr = (r) => ({ ...r, qrEnvelopeHash: qh });

function review({ rec, time, pq }) {
  const c = randomId();
  const { envelope: env, stamps } = envelope(
    { v: 1, typ: 'rev-comment', f: practice.documentId, c, h: sha256hex(rec.Content), rh: recordHash(withQr(rec)), rv: 1, qh, iat: sec(time) },
    pq,
  );
  return { c, envelope: env, stamps, time };
}

function redactionSeal(r, displayed, time) {
  const { envelope: env } = envelope({
    v: 1, typ: 'rev-redaction', c: r.c, eh: sha256hex(r.envelope),
    h: sha256hex(displayed.Content), rh: recordHash(withQr(displayed)), rv: 1, iat: sec(time),
  });
  return { envelope: env, kid: ED.kid, ed25519Pub: b64(ED.pub) };
}

function pkg(r, rec, redaction, created) {
  return {
    type: 'mcgesund-verification-package',
    version: 1,
    createdAt: iso(created),
    demo: DEMO_NOTE,
    comment: r.c,
    envelope: r.envelope,
    record: rec,
    attestation: {
      envelope: { kid: ED.kid, ed25519Pub: b64(ED.pub) },
      stamps: r.stamps.map((s) => stamp(KEYS[s.variant], s.sig)),
      payloadHash: null,
      revoked: false,
      revokedAt: null,
      anchor: null, // = key proof of demo-ed, set below
      qr: structuredClone(qrAttestation),
      commentAnchor: null, // set below
      redaction,
    },
    keyDirectory: 'examples/demo-keys.json',
  };
}

// 1. Unchanged, envelope v4 with ML-DSA-87
const r1 = record('Very friendly team and short waiting time.', [5, 5, 4, 5], 18.4);
const v1 = review({ rec: r1, time: now - 30 * HOUR, pq: [ML] });
const p1 = pkg(v1, r1, null, now - 5 * 60e3);

// 2. Redacted (name removed), envelope v4 with ML-DSA-87
const r2orig = record('Very friendly team, Jane Doe explained everything clearly.', [5, 4, 5, 5], 31.7);
const r2 = { ...r2orig, Content: 'Very friendly team, [name removed] explained everything clearly.' };
const v2 = review({ rec: r2orig, time: now - 28 * HOUR, pq: [ML] });
const p2 = pkg(v2, r2, redactionSeal(v2, r2, now - 20 * HOUR), now - 4 * 60e3);

// 3. In the transparency log, older envelope v3 (Ed25519 only), redacted later
const r3orig = record('Short waiting time, and John Smith at the front desk was very helpful.', [4, 5, 4, 4], 12.2);
const r3 = { ...r3orig, Content: 'Short waiting time, and [name removed] at the front desk was very helpful.' };
const v3 = review({ rec: r3orig, time: now - 26 * HOUR, pq: [] });
const seal3 = redactionSeal(v3, r3, now - 3 * HOUR);
const p3 = pkg(v3, r3, seal3, now - 3 * 60e3);

// ---------------------------------------------------------------------------
// Transparency log: 5 entries, 3 of them for review 3, the rest made up
// ---------------------------------------------------------------------------

const salt = () => randomBytes(16).toString('hex');
const logStart = now - 27 * HOUR;
const entries = [
  { kind: 'submitted', at: iso(v3.time), category: null, commentDocumentId: v3.c, envelopeHash: sha256hex(v3.envelope), sealHash: null },
  { kind: 'submitted', at: iso(now - 25 * HOUR), category: null, commentDocumentId: randomId(), envelopeHash: randomBytes(32).toString('hex'), sealHash: null },
  { kind: 'rejected', at: iso(now - 24 * HOUR), category: 'off_topic', commentDocumentId: randomId(), envelopeHash: randomBytes(32).toString('hex'), sealHash: null },
  { kind: 'published', at: iso(now - 22 * HOUR), category: null, commentDocumentId: v3.c, envelopeHash: sha256hex(v3.envelope), sealHash: null },
  { kind: 'redacted', at: iso(now - 3 * HOUR), category: 'personal_data', commentDocumentId: v3.c, envelopeHash: sha256hex(v3.envelope), sealHash: sha256hex(seal3.envelope) },
].map((e, index) => {
  const full = { index, ...e, firmaDocumentId: practice.documentId, salt: salt() };
  // Other reviews belong to other (made-up) companies.
  if (e.commentDocumentId !== v3.c) full.firmaDocumentId = randomId();
  return { ...full, leafHash: leafHash(full), erased: false };
});
const leaves = entries.map((e) => Buffer.from(e.leafHash, 'hex'));
const split = (n) => { let k = 1; while (k * 2 < n) k *= 2; return k; };
const inclusion = (m, d) => {
  if (d.length === 1) return [];
  const k = split(d.length);
  return m < k ? [...inclusion(m, d.slice(0, k)), merkleRoot(d.slice(k))] : [...inclusion(m - k, d.slice(k)), merkleRoot(d.slice(0, k))];
};
const rootHash = merkleRoot(leaves).toString('hex');
const signedAt = new Date(now - 2 * HOUR);
signedAt.setUTCMinutes(20, 0, 0);
const treeHeadEnvelope = envelope(
  { v: 1, typ: 'tlog-root', n: entries.length, r: rootHash, iat: sec(signedAt.getTime()) },
  [ML],
).envelope;
const logProof = {
  demo: DEMO_NOTE,
  pending: 0,
  logStart: iso(logStart),
  root: { treeSize: entries.length, rootHash, signedAt: signedAt.toISOString(), envelope: treeHeadEnvelope, anchor: null },
  entries: entries
    .filter((e) => e.commentDocumentId === v3.c)
    .map((entry) => ({ entry, inclusionProof: inclusion(entry.index, leaves).map((x) => x.toString('hex')) })),
};

// ---------------------------------------------------------------------------
// Key directory
// ---------------------------------------------------------------------------

const directory = {
  version: 1,
  issuer: 'McGesund Verify demo — not real McGesund keys',
  demo: DEMO_NOTE,
  generatedAt: iso(now),
  anchorCommitment: {
    hash: 'sha256',
    format: 'kid:<kid>\nvariant:<algorithm>\npubkey:<publicKey base64>\nactiveFrom:<validFrom ISO-8601>',
    proof: 'anchor.otsProof is an OpenTimestamps proof (base64) over this sha256 digest',
  },
  keys: [ED, ML, SLH].map((k) => ({
    kid: k.kid,
    algorithm: k.algorithm,
    algorithmName: k.algorithmName,
    standard: k.standard,
    format: 'v1',
    publicKey: b64(k.pub),
    validFrom: validFrom.toISOString(),
    validUntil: validUntil.toISOString(),
    revoked: false,
    revokedAt: null,
    revokedReason: null,
    anchor: null,
  })),
};
const keyCommitment = (d) =>
  sha256hex(`kid:${d.kid}\nvariant:${d.algorithm}\npubkey:${d.publicKey}\nactiveFrom:${new Date(d.validFrom).toISOString()}`);

// ---------------------------------------------------------------------------
// OpenTimestamps: all digests to the calendars in ONE call
// ---------------------------------------------------------------------------

const targets = [
  ...directory.keys.map((d) => ({
    name: `Key ${d.kid}`, digest: keyCommitment(d),
    set: (p) => { d.anchor = { status: 'anchoring', bitcoinBlock: null, bitcoinBlockHash: null, confirmedAt: null, otsProof: p }; },
    get: () => d.anchor.otsProof,
  })),
  ...[['unchanged', p1], ['redacted', p2], ['in-log', p3]].map(([n, p]) => ({
    name: `Envelope ${n}`, digest: sha256hex(p.envelope),
    set: (proof) => { p.attestation.commentAnchor = { status: 'anchoring', btcBlock: null, btcAnchoredAt: null, otsProof: proof }; },
    get: () => p.attestation.commentAnchor.otsProof,
  })),
  {
    name: 'Tree head', digest: sha256hex(treeHeadEnvelope),
    set: (p) => { logProof.root.anchor = { status: 'anchoring', btcBlock: null, otsProof: p }; },
    get: () => logProof.root.anchor.otsProof,
  },
];

for (const t of targets) t.set(b64(writeProof(await stamp(Buffer.from(t.digest, 'hex')))));

const edAnchor = directory.keys[0].anchor;
for (const p of [p1, p2, p3]) {
  p.attestation.anchor = { status: edAnchor.status, btcBlock: edAnchor.bitcoinBlock, btcAnchoredAt: edAnchor.confirmedAt, otsProof: edAnchor.otsProof };
}

// ---------------------------------------------------------------------------
// Self-check with the verifier before anything is written
// ---------------------------------------------------------------------------

const problems = [];
for (const t of targets) if (proofDigest(t.get()) !== t.digest) problems.push(`${t.name}: OTS proof does not match its digest`);
for (const [n, p] of [['unchanged', p1], ['redacted', p2], ['in-log', p3]]) {
  // With anchor status "anchored" (simulated) the tool additionally compares the proof digests.
  const simulated = structuredClone(p);
  simulated.attestation.commentAnchor.status = 'anchored';
  const kd = structuredClone(directory);
  for (const k of kd.keys) k.anchor.status = 'anchored';
  for (const [x, keys] of [[p, directory], [simulated, kd]]) {
    for (const f of await verifyPackage(x, { keys })) if (f.kind === 'error') problems.push(`${n}: ${f.text}`);
  }
  if (readEnvelope(p.envelope).payload.c !== p.comment) problems.push(`${n}: comment ID mismatch`);
}
const kids = new Map(directory.keys.map((k) => [k.kid, k]));
for (const [kind, text] of verifyTreeHead(logProof.root, kids)) if (kind !== 'ok') problems.push(`Tree head: ${text}`);
{
  const original = globalThis.fetch;
  globalThis.fetch = async () => new Response(JSON.stringify(logProof), { status: 200 });
  try {
    for (const [kind, text] of await verifyReviewInLog(p3, { api: 'http://demo.invalid', keys: kids })) {
      if (kind === 'error') problems.push(`Log: ${text}`);
    }
  } finally {
    globalThis.fetch = original;
  }
}
if (problems.length) {
  console.error('Self-check failed, nothing written:\n  ' + problems.join('\n  '));
  process.exit(1);
}

// ---------------------------------------------------------------------------
// Write
// ---------------------------------------------------------------------------

const write = (name, obj) => {
  fs.writeFileSync(new URL(name, OUT), JSON.stringify(obj, null, 2) + '\n', 'utf8');
  console.log(`written: examples/${name}`);
};
write('demo-keys.json', directory);
write('package-unchanged.json', p1);
write('package-redacted.json', p2);
write('package-in-log.json', p3);
write('log-proof.json', logProof);
console.log(`\n${targets.length} digests submitted to OpenTimestamps calendars; proofs are pending.`);
console.log('Run `node examples/update.js` in a few hours (best the next day) to add the Bitcoin confirmations.');
